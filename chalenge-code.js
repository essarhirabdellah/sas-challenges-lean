function even(start,over){
    while(start <= over){
        if(start%2 == 0){
            console.log(`this number ${start} even`);
        }
        start++
    }
}
even(1,100);

function check_even(start,over){
    let i = start;
    let sum = 0;
    while(i <= over){
       loopme = start + over + i;
       if(loopme%2 == 0) {
        sum += loopme;
       }
       i++;
    }
    return `this the sum of all even numbers ${sum}`;
}
console.log(check_even(1,10));

